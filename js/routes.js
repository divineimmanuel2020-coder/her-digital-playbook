/** "blog/some-id.html" — no leading slash, for use with BASE. */
export function itemRelPath(item) {
  return `${item.type === 'tool' ? TOOL_DIR : ARTICLE_DIR}/${item.id}.html`;
}

/** "/blog/some-id.html" — root-absolute, for static HTML. */
export function itemPath(item) {
  return `/${itemRelPath(item)}`;
}

/** Same as itemPath, starting from an id. Falls back to /blog/. */
export function itemPathById(id) {
  const item = findItemById(id);
  return item ? itemPath(item) : `/${ARTICLE_DIR}/${id}.html`;
}

export function itemRelPathById(id) {
  return itemPathById(id).slice(1);
}
