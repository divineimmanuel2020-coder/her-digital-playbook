/* =============================================
   ROUTES.JS
   The one place that decides where an article or tool lives.

   Every article gets its own real, static file:
     /blog/<id>.html     (stories + articles)
     /tools/<id>.html    (free tools)

   Those files are generated by `node scripts/build.mjs` and
   contain the full text in the raw HTML — nothing is fetched or
   assembled by JavaScript before a crawler can read it.

   No DOM access here on purpose: this file is imported by the
   browser scripts AND by the Node build script.
   ============================================= */

